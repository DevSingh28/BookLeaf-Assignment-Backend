-- File: bookleaf_database.sql
-- BookLeaf Author Support & Communication Portal
-- PostgreSQL 13+ recommended. Run this in the target database using pgAdmin.
-- The script creates schema + indexes + triggers + reference data + supplied sample authors/books.
-- It does NOT create a database; create/select your database first in pgAdmin.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =========================
-- 1. Identity and author profiles
-- =========================
CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    external_id VARCHAR(80) UNIQUE,
    full_name VARCHAR(160) NOT NULL,
    email VARCHAR(320) NOT NULL,
    phone VARCHAR(40),
    role VARCHAR(20) NOT NULL DEFAULT 'author'
        CHECK (role IN ('author', 'support', 'admin')),
    password_hash TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    email_verified_at TIMESTAMPTZ,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Case-insensitive uniqueness without forcing email display casing.
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower ON users (LOWER(email));
CREATE INDEX IF NOT EXISTS idx_users_role_active ON users (role, is_active);
CREATE INDEX IF NOT EXISTS idx_users_created_at ON users (created_at DESC);

CREATE TABLE IF NOT EXISTS author_profiles (
    user_id UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    city VARCHAR(120),
    joined_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_author_profiles_city ON author_profiles (city);

-- =========================
-- 2. Books, marketplaces, and royalty snapshot
-- =========================
CREATE TABLE IF NOT EXISTS books (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    external_id VARCHAR(80) UNIQUE,
    author_id UUID NOT NULL REFERENCES author_profiles(user_id) ON DELETE RESTRICT,
    title VARCHAR(300) NOT NULL,
    isbn VARCHAR(32),
    genre VARCHAR(160),
    publication_date DATE,
    production_status VARCHAR(100) NOT NULL,
    mrp NUMERIC(12,2) CHECK (mrp IS NULL OR mrp >= 0),
    author_royalty_per_copy NUMERIC(12,2) CHECK (author_royalty_per_copy IS NULL OR author_royalty_per_copy >= 0),
    print_partner VARCHAR(120),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_books_author ON books (author_id);
CREATE INDEX IF NOT EXISTS idx_books_status ON books (production_status);
CREATE INDEX IF NOT EXISTS idx_books_publication_date ON books (publication_date DESC) WHERE publication_date IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_books_title_lower ON books (LOWER(title));
CREATE INDEX IF NOT EXISTS idx_books_isbn ON books (isbn) WHERE isbn IS NOT NULL;
-- Supports a composite FK from tickets so a ticket cannot reference another author's book.
CREATE UNIQUE INDEX IF NOT EXISTS uq_books_id_author ON books (id, author_id);

CREATE TABLE IF NOT EXISTS sales_channels (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS book_sales_channels (
    book_id UUID NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    channel_id SMALLINT NOT NULL REFERENCES sales_channels(id) ON DELETE RESTRICT,
    listing_status VARCHAR(30) NOT NULL DEFAULT 'listed'
        CHECK (listing_status IN ('listed', 'pending', 'unavailable', 'delisted')),
    listing_url TEXT,
    last_synced_at TIMESTAMPTZ,
    PRIMARY KEY (book_id, channel_id)
);
CREATE INDEX IF NOT EXISTS idx_book_channels_channel_status ON book_sales_channels (channel_id, listing_status);

-- Imported dataset contains aggregates, not individual sales or payout ledger rows.
-- Keep imported figures as a one-row-per-book snapshot; future transactions can be added separately.
CREATE TABLE IF NOT EXISTS book_royalty_summaries (
    book_id UUID PRIMARY KEY REFERENCES books(id) ON DELETE CASCADE,
    total_copies_sold INTEGER NOT NULL DEFAULT 0 CHECK (total_copies_sold >= 0),
    total_royalty_earned NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total_royalty_earned >= 0),
    royalty_paid NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (royalty_paid >= 0),
    royalty_pending NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (royalty_pending >= 0),
    last_royalty_payout_date DATE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (total_royalty_earned = royalty_paid + royalty_pending)
);
CREATE INDEX IF NOT EXISTS idx_royalty_pending ON book_royalty_summaries (royalty_pending DESC) WHERE royalty_pending > 0;
CREATE INDEX IF NOT EXISTS idx_royalty_last_payout ON book_royalty_summaries (last_royalty_payout_date DESC) WHERE last_royalty_payout_date IS NOT NULL;

-- =========================
-- 3. Support ticket reference tables
-- =========================
CREATE TABLE IF NOT EXISTS ticket_categories (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS ticket_statuses (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL UNIQUE,
    is_closed BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order SMALLINT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS ticket_priorities (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(20) NOT NULL UNIQUE,
    sort_order SMALLINT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS tickets (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ticket_number BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,
    author_id UUID NOT NULL REFERENCES author_profiles(user_id) ON DELETE RESTRICT,
    book_id UUID REFERENCES books(id) ON DELETE SET NULL,
    category_id SMALLINT NOT NULL REFERENCES ticket_categories(id) ON DELETE RESTRICT,
    status_id SMALLINT NOT NULL REFERENCES ticket_statuses(id) ON DELETE RESTRICT,
    priority_id SMALLINT NOT NULL REFERENCES ticket_priorities(id) ON DELETE RESTRICT,
    subject VARCHAR(240) NOT NULL,
    description TEXT NOT NULL,
    assigned_to UUID REFERENCES users(id) ON DELETE SET NULL,
    created_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    resolved_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,
    last_message_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (LENGTH(BTRIM(subject)) > 0),
    CHECK (LENGTH(BTRIM(description)) > 0),
    FOREIGN KEY (book_id, author_id) REFERENCES books(id, author_id)
);
CREATE INDEX IF NOT EXISTS idx_tickets_author_recent ON tickets (author_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_tickets_status_priority_recent ON tickets (status_id, priority_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_tickets_category_created ON tickets (category_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_tickets_assignee_status ON tickets (assigned_to, status_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_tickets_created_at ON tickets (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_tickets_last_message ON tickets (last_message_at DESC);
CREATE INDEX IF NOT EXISTS idx_tickets_open_oldest ON tickets (created_at ASC)
    WHERE resolved_at IS NULL AND closed_at IS NULL;

CREATE TABLE IF NOT EXISTS ticket_messages (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ticket_id UUID NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    sender_id UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    message_type VARCHAR(20) NOT NULL DEFAULT 'reply'
        CHECK (message_type IN ('reply', 'internal_note', 'system_event')),
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    edited_at TIMESTAMPTZ,
    CHECK (LENGTH(BTRIM(body)) > 0)
);
CREATE INDEX IF NOT EXISTS idx_ticket_messages_ticket_time ON ticket_messages (ticket_id, created_at ASC);
CREATE INDEX IF NOT EXISTS idx_ticket_messages_sender_time ON ticket_messages (sender_id, created_at DESC);

CREATE TABLE IF NOT EXISTS ticket_attachments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ticket_id UUID NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    message_id UUID REFERENCES ticket_messages(id) ON DELETE CASCADE,
    uploaded_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    original_filename VARCHAR(255) NOT NULL,
    storage_key TEXT NOT NULL,
    mime_type VARCHAR(150) NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ticket_attachments_ticket ON ticket_attachments (ticket_id, created_at);

CREATE TABLE IF NOT EXISTS ticket_status_history (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ticket_id UUID NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    changed_by UUID REFERENCES users(id) ON DELETE SET NULL,
    old_status_id SMALLINT REFERENCES ticket_statuses(id) ON DELETE SET NULL,
    new_status_id SMALLINT NOT NULL REFERENCES ticket_statuses(id) ON DELETE RESTRICT,
    note TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ticket_status_history_ticket_time ON ticket_status_history (ticket_id, changed_at DESC);

-- AI outputs are suggestions, never authoritative ticket state; agents can override them.
CREATE TABLE IF NOT EXISTS ticket_ai_assessments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ticket_id UUID NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    suggested_category_id SMALLINT REFERENCES ticket_categories(id) ON DELETE SET NULL,
    suggested_priority_id SMALLINT REFERENCES ticket_priorities(id) ON DELETE SET NULL,
    category_confidence NUMERIC(5,4) CHECK (category_confidence IS NULL OR category_confidence BETWEEN 0 AND 1),
    priority_confidence NUMERIC(5,4) CHECK (priority_confidence IS NULL OR priority_confidence BETWEEN 0 AND 1),
    reasoning TEXT,
    response_draft TEXT,
    model_name VARCHAR(160),
    accepted BOOLEAN,
    reviewed_by UUID REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ai_assessments_ticket_recent ON ticket_ai_assessments (ticket_id, created_at DESC);

-- Knowledge base supports grounding AI drafts in curated internal guidance.
CREATE TABLE IF NOT EXISTS knowledge_base_articles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    slug VARCHAR(180) NOT NULL UNIQUE,
    title VARCHAR(240) NOT NULL,
    category VARCHAR(80),
    content TEXT NOT NULL,
    keywords TEXT[] NOT NULL DEFAULT '{}',
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_by UUID REFERENCES users(id) ON DELETE SET NULL,
    updated_by UUID REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_kb_published_category ON knowledge_base_articles (category, updated_at DESC) WHERE is_published = TRUE;
CREATE INDEX IF NOT EXISTS idx_kb_keywords_gin ON knowledge_base_articles USING GIN (keywords);

-- Normalized traceability: which knowledge-base articles grounded each AI assessment.
CREATE TABLE IF NOT EXISTS ticket_ai_assessment_articles (
    assessment_id UUID NOT NULL REFERENCES ticket_ai_assessments(id) ON DELETE CASCADE,
    article_id UUID NOT NULL REFERENCES knowledge_base_articles(id) ON DELETE RESTRICT,
    PRIMARY KEY (assessment_id, article_id)
);
CREATE INDEX IF NOT EXISTS idx_ai_assessment_articles_article ON ticket_ai_assessment_articles (article_id);

-- =========================
-- 4. updated_at trigger
-- =========================
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_author_profiles_updated_at ON author_profiles;
CREATE TRIGGER trg_author_profiles_updated_at BEFORE UPDATE ON author_profiles FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_books_updated_at ON books;
CREATE TRIGGER trg_books_updated_at BEFORE UPDATE ON books FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_book_royalty_summaries_updated_at ON book_royalty_summaries;
CREATE TRIGGER trg_book_royalty_summaries_updated_at BEFORE UPDATE ON book_royalty_summaries FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_tickets_updated_at ON tickets;
CREATE TRIGGER trg_tickets_updated_at BEFORE UPDATE ON tickets FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_kb_updated_at ON knowledge_base_articles;
CREATE TRIGGER trg_kb_updated_at BEFORE UPDATE ON knowledge_base_articles FOR EACH ROW EXECUTE FUNCTION set_updated_at();

